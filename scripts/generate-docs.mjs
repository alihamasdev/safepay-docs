import { generateFiles } from "fumadocs-openapi";
import { createOpenAPI } from "fumadocs-openapi/server";

import { paymentActions } from "../src/lib/payments-data.ts";

const openapi = createOpenAPI({
	input: ["./public/openapi.json"],
});

await generateFiles({
	input: openapi,
	output: "./content/docs/api-reference",
	per: "operation",
	groupBy: (op) => {
		const tag = op.item?.tags?.[0] || "Other";
		if (tag === "API Authentication") return "api-authentication";
		if (tag === "API Keys") return "api-keys";
		if (tag.startsWith("Merchant Shoppers")) {
			const sub = tag
				.replace("Merchant Shoppers - ", "")
				.trim()
				.toLowerCase()
				.replace(/[^a-z0-9]+/g, "-");
			return `merchant-shoppers/${sub}`;
		}
		if (tag.startsWith("Payments")) {
			const sub = tag
				.replace("Payments - ", "")
				.trim()
				.toLowerCase()
				.replace(/[^a-z0-9]+/g, "-");
			return `payments/${sub}`;
		}
		if (tag.startsWith("Subscriptions")) {
			const sub = tag
				.replace("Subscriptions - ", "")
				.trim()
				.toLowerCase()
				.replace(/[^a-z0-9]+/g, "-");
			return `subscriptions/${sub}`;
		}
		if (tag === "Quick Links") {
			return "quick-links/v1";
		}
		if (tag === "Quick Links - V2") {
			return "quick-links/v2";
		}
		if (tag.startsWith("Safepay Shoppers")) {
			const sub = tag
				.replace("Safepay Shoppers - ", "")
				.trim()
				.toLowerCase()
				.replace(/[^a-z0-9]+/g, "-");
			return `safepay-shoppers/${sub}`;
		}
		return "other";
	},
	meta: true,
	beforeWrite(files) {
		// 1. Root meta.json: define groups as separators (labels) and folders
		const rootMeta = files.find((f) => f.path === "meta.json");
		if (rootMeta) {
			const parsed = JSON.parse(rootMeta.content);
			parsed.title = "API Reference";
			parsed.root = true;
			parsed.pages = [
				"index",
				"---API Authentication---",
				"...api-authentication",
				"---API Keys---",
				"...api-keys",
				"---Merchant Shoppers---",
				"...merchant-shoppers",
				"---Payments---",
				"...payments",
				"---Subscriptions---",
				"...subscriptions",
				"---Quick Links---",
				"...quick-links",
				"---Safepay Shoppers---",
				"...safepay-shoppers",
			];
			rootMeta.content = JSON.stringify(parsed, null, 2);
		}

		// 2. Add intermediate meta.json for the 5 nested primary folders
		files.push({
			path: "merchant-shoppers/meta.json",
			content: JSON.stringify(
				{
					title: "Merchant Shoppers",
					pages: ["crud", "customer-payment-methods", "addresses"],
				},
				null,
				2,
			),
		});

		files.push({
			path: "payments/meta.json",
			content: JSON.stringify(
				{
					title: "Payments",
					pages: ["setup", "order", "configuration", "cancellations", "reporting", "meta", "webhooks"],
				},
				null,
				2,
			),
		});

		files.push({
			path: "subscriptions/meta.json",
			content: JSON.stringify(
				{
					title: "Subscriptions",
					pages: ["plans", "subscriptions", "transactions"],
				},
				null,
				2,
			),
		});

		files.push({
			path: "quick-links/meta.json",
			content: JSON.stringify(
				{
					title: "Quick Links",
					pages: ["v1", "v2"],
				},
				null,
				2,
			),
		});

		files.push({
			path: "safepay-shoppers/meta.json",
			content: JSON.stringify(
				{
					title: "Safepay Shoppers",
					pages: ["crud", "payment-methods"],
				},
				null,
				2,
			),
		});

		// 3. Remove single default generated pages for setup and order
		for (let i = files.length - 1; i >= 0; i--) {
			const p = files[i].path;
			if (p.includes("payments/setup/paymentsSetupPayment") || p.includes("payments/order/paymentsOrderGenerateCaptureContext")) {
				files.splice(i, 1);
			}
		}

		function makeMdx({ title, description, path, method, action }) {
			const safeDesc = description ? description.split("\n").join("\n  ") : title;
			return `---
title: ${title}
description: |-
  ${safeDesc}
full: true
_openapi:
  preload:
    - ./public/openapi.json
---

{/* This file was generated by Fumadocs. */}

export default function Layout(props) {
\tconst { OpenAPIPage } = props.components ?? {};
\treturn (
\t\t<>
\t\t\t{props.children}
\t\t\t<OpenAPIPage
\t\t\t\tdocument="./public/openapi.json"
\t\t\t\toperations={[{ path: "${path}", method: "${method}" }]}
\t\t\t\taction="${action}"
\t\t\t/>
\t\t</>
\t);
}
`;
		}

		// 4. Add the 6 Setup pages
		const setupPages = [
			{ slug: "payment", title: "Payment", action: "payment" },
			{ slug: "subscription", title: "Subscription", action: "subscription" },
			{ slug: "instrument", title: "Instrument", action: "instrument" },
			{ slug: "unscheduled-cof", title: "Unscheduled COF", action: "unscheduled-cof" },
			{ slug: "google-pay", title: "Google Pay", action: "google-pay" },
			{ slug: "raast", title: "Raast", action: "raast" },
		];

		for (const sp of setupPages) {
			const actionData = paymentActions[sp.action];
			files.push({
				path: `payments/setup/${sp.slug}.mdx`,
				content: makeMdx({
					title: sp.title,
					description: actionData?.description || sp.title,
					path: "/order/payments/v3",
					method: "post",
					action: sp.action,
				}),
			});
		}

		const setupMeta = files.find((f) => f.path === "payments/setup/meta.json");
		const setupMetaContent = JSON.stringify(
			{
				title: "Setup",
				pages: setupPages.map((p) => p.slug),
			},
			null,
			2,
		);
		if (setupMeta) {
			setupMeta.content = setupMetaContent;
		} else {
			files.push({ path: "payments/setup/meta.json", content: setupMetaContent });
		}

		// 5. Add the 9 Order pages
		const orderPages = [
			{ slug: "generate-capture-context", title: "Generate Capture Context", action: "generate-capture-context" },
			{ slug: "process-transient-token", title: "Process Transient Token", action: "process-transient-token" },
			{ slug: "payer-authentication-setup", title: "Payer Authentication Setup", action: "payer-authentication-setup" },
			{ slug: "enrollment", title: "Enrollment", action: "enrollment" },
			{ slug: "authorization", title: "Authorization", action: "authorization" },
			{ slug: "capture", title: "Capture", action: "capture" },
			{ slug: "reversal", title: "Reversal", action: "reversal" },
			{ slug: "google-pay", title: "Google Pay", action: "order-google-pay" },
			{ slug: "raast", title: "Raast", action: "order-raast" },
		];

		for (const op of orderPages) {
			const actionData = paymentActions[op.action];
			files.push({
				path: `payments/order/${op.slug}.mdx`,
				content: makeMdx({
					title: op.title,
					description: actionData?.description || op.title,
					path: "/order/payments/v3/{tracker}",
					method: "post",
					action: op.action,
				}),
			});
		}

		const orderMeta = files.find((f) => f.path === "payments/order/meta.json");
		const orderMetaContent = JSON.stringify(
			{
				title: "Order",
				pages: orderPages.map((p) => p.slug),
			},
			null,
			2,
		);
		if (orderMeta) {
			orderMeta.content = orderMetaContent;
		} else {
			files.push({ path: "payments/order/meta.json", content: orderMetaContent });
		}

		// 6. Set human-friendly titles for subfolder meta.json files
		const subTitleMap = {
			"api-authentication/meta.json": "API Authentication",
			"api-keys/meta.json": "API Keys",
			"merchant-shoppers/crud/meta.json": "CRUD",
			"merchant-shoppers/customer-payment-methods/meta.json": "Customer Payment Methods",
			"merchant-shoppers/addresses/meta.json": "Addresses",
			"payments/configuration/meta.json": "Configuration",
			"payments/cancellations/meta.json": "Cancellations",
			"payments/reporting/meta.json": "Reporting",
			"payments/meta/meta.json": "Meta",
			"payments/webhooks/meta.json": "Webhooks",
			"subscriptions/plans/meta.json": "Plans",
			"subscriptions/subscriptions/meta.json": "Subscriptions",
			"subscriptions/transactions/meta.json": "Transactions",
			"quick-links/v1/meta.json": "V1",
			"quick-links/v2/meta.json": "V2",
			"safepay-shoppers/crud/meta.json": "CRUD",
			"safepay-shoppers/payment-methods/meta.json": "Payment Methods",
		};

		for (const file of files) {
			if (subTitleMap[file.path]) {
				try {
					const meta = JSON.parse(file.content);
					meta.title = subTitleMap[file.path];
					file.content = JSON.stringify(meta, null, 2);
				} catch {}
			}
		}
	},
});

console.log("Successfully generated hierarchical API reference docs!");
